#!/bin/bash

# Функция для обработки сигнала SIGINT (Ctrl+C)
cleanup() {
    echo -e "\nПолучен сигнал SIGINT (Ctrl+C). Завершаем процесс с PID $pid..."
    kill -TERM "$pid" 2>/dev/null
    wait "$pid" 2>/dev/null
    echo "Процесс с PID $pid завершён. Выход из скрипта."
    exit 0
}

# Устанавливаем обработчик сигнала SIGINT
trap cleanup SIGINT

echo "Запуск процесса с ~90% загрузкой CPU..."

# Запускаем процесс, который будет нагружать CPU
# Используем цикл с sleep для регулировки нагрузки
(
    while true; do
        # Активная фаза: нагружаем CPU (пустой цикл)
        for ((i=0; i<10000000; i++)); do
            : # Пустая операция — нагружает CPU
        done
        # Пассивная фаза: даём CPU отдохнуть (снижаем нагрузку до ~90%)
        sleep 0.05
    done
) &

# Сохраняем PID запущенного фонового процесса
pid=$!

echo "PID процесса: $pid"
echo "Для остановки нажмите Ctrl+C"

# Ждём завершения процесса (он бесконечный, поэтому ждём сигнала)
wait "$pid"
