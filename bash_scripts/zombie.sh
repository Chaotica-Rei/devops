#!/bin/bash

echo "Демонстрация создания зомби-процесса"
echo "Текущий PID скрипта: $$"

# Функция для создания дочернего процесса
create_zombie() {
    echo "Дочерний процесс запущен, PID: $$"
    sleep 2  # Даём время посмотреть
    echo "Дочерний процесс завершает работу"
    exit 0  # Завершаем дочерний процесс
}

# Запускаем дочерний процесс в фоне
create_zombie &

CHILD_PID=$!
echo "Дочерний процесс запущен с PID: $CHILD_PID"

# Ждём немного, чтобы дочерний процесс успел завершиться
sleep 3

echo "Дочерний процесс уже завершился, но родитель не вызвал wait()"
echo "Проверяем наличие зомби-процесса..."

# Ищем зомби-процессы с нашим родителем
ps -o pid,ppid,stat,comm -p $CHILD_PID 2>/dev/null || echo "Процесс уже очищен или не найден"

echo "Полный список зомби-процессов в системе:"
ps aux | awk '$8 ~ /Z/ {print}'

echo "Чтобы очистить зомби, родительский процесс должен вызвать wait()."
echo "В этом скрипте мы не делаем этого намеренно — для демонстрации."

# Показываем, что родитель всё ещё жив
echo "Родительский процесс ($$) продолжает работать..."
sleep 5
echo "Завершение родительского процесса. Зомби будет очищен системой."
